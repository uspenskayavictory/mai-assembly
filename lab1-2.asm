.data                               
out:  .asciz "Enter x: "            # ввод данных с консоли
space:   .asciz " "                 # пробел 
newline: .asciz "\n"                # перевод строки

.text                               # начало кода
main:                             
    la   a0, out                    # a0 - адрес ввода данных с консоли
    li   a7, 4                      # a7 = 4 - вызов вывода строки 
    ecall                           # выводим строки с вводом данных с консоли

    li   a7, 5                      # a7 = 5 - чтение введенного числа
    ecall                           # введенное число х записывается в a0

    mv   t0, a0                     # t0 = x
    li   t1, 121                    # t1 = y = 121 (номер группы)
    li   t2, 17                     # t2 = h = 17 (номер студента, шаг)

    ble  t0, t1, x_is_min           # если x <= y, то x - минимум, переходим на x_is_min

    mv   s0, t1                     # иначе минимум = y: s0 = начало диапазона
    mv   s1, t0                     # максимум = x: s1 = конец диапазона
    j    loop                       # переходим к циклу вывода

x_is_min:                           # сюда попадаем, если x <= y
    mv   s0, t0                     # s0 = min = x
    mv   s1, t1                     # s1 = max = y

loop:                               # начало цикла вывода
    bgt  s0, s1, done               # если текущее значение > max, диапазон закончился

    mv   a0, s0                     # a0 = текущее значение
    li   a7, 1                      # a7 = 1: системный вызов "вывести целое число"
    ecall                           # выводим текущее значение

    la   a0, space                  # a0 = адрес строки с пробелом
    li   a7, 4                      # a7 = 4: вывести строку
    ecall                           # выводим пробел-разделитель

    add  s0, s0, t2                 # текущее значение += h
    j    loop                       # возвращаемся к началу цикла

done:                               # конец цикла
    la   a0, newline                # a0 = адрес перевода строки
    li   a7, 4                      # a7 = 4: вывести строку
    ecall                           # переходим на новую строку

    li   a7, 10                     # a7 = 10: останов
    ecall                           # выход